-- school_domain_enabled(): app_settings.key='school_domain_enabled' 값이 'true'인지
create or replace function public.school_domain_enabled()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select value from public.app_settings where key = 'school_domain_enabled'),
    'false'
  ) = 'true';
$$;

revoke all on function public.school_domain_enabled() from public;
grant execute on function public.school_domain_enabled() to anon, authenticated;

-- school_domain_value(): app_settings.key='school_domain' 값
create or replace function public.school_domain_value()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select value from public.app_settings where key = 'school_domain'),
    ''
  );
$$;

revoke all on function public.school_domain_value() from public;
grant execute on function public.school_domain_value() to anon, authenticated;

-- is_school_domain_email(): 도메인 사용이 켜져 있고, 주어진 이메일이 그 도메인으로 끝나는지
create or replace function public.is_school_domain_email(target_email text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    public.school_domain_enabled()
    and length(public.school_domain_value()) > 0
    and lower(coalesce(target_email, '')) like ('%@' || lower(public.school_domain_value()));
$$;

revoke all on function public.is_school_domain_email(text) from public;
grant execute on function public.is_school_domain_email(text) to anon, authenticated;

