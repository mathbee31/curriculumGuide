-- ── student_emails 테이블: 학생 허용목록 (teacher_emails와 동일 패턴) ──
create table if not exists public.student_emails (
  email      text primary key,
  created_at timestamptz not null default now()
);

create or replace function public.is_student()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.student_emails s
    where lower(s.email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

revoke all on function public.is_student() from public;
grant execute on function public.is_student() to authenticated;

alter table public.student_emails enable row level security;

