-- ── student_requests 테이블: 학생 가입 신청 (teacher_requests와 동일 패턴) ──
create table if not exists public.student_requests (
  id          uuid        default gen_random_uuid() primary key,
  email       text        not null,
  name        text        not null,
  grade       text        not null default '',
  class_no    text        not null default '',
  number      text        not null default '',
  auth_method text        not null default 'email', -- 'google' | 'email'
  message     text        default '',
  status      text        not null default 'pending', -- 'pending' | 'approved' | 'rejected'
  portal_url  text        not null default '',  -- 실제 수강신청/결과 확인 개인별 웹주소(학생-교사정보.xlsx의 URL 열)
