-- is_admin(): admins 테이블에 등록된 계정인지 확인 (다른 테이블의 RLS 정책에서 참조)
-- ⚠ set row_security = off 필수: SECURITY DEFINER만으로는 부족하다. 이 함수 없이
--   admins_bootstrap_insert 정책의 WITH CHECK가 "select 1 from admins" 같은 일반
--   서브쿼리를 직접 쓰면, 그 서브쿼리는 호출한 role(anon/authenticated) 권한으로
--   실행되어 admins_self_or_admin_read SELECT 정책이 다시 적용되고, 그 정책이 다시
--   is_admin()을 호출하면서 무한 재귀(`infinite recursion detected in policy for
--   relation "admins"`, 42P17)에 빠진다. row_security = off는 이 함수 소유자
--   (postgres, bypassrls)가 내부 조회 시 RLS를 절대 다시 적용하지 않도록 못박아
--   재귀 경로를 원천적으로 끊는다.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
set row_security = off
as $$
  select exists (
    select 1 from public.admins a
    where lower(a.email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

-- admin_exists(): 관리자가 한 명도 없는지 여부만 노출 (로그인 전 anon 호출용)
-- ⚠ is_admin()과 동일한 이유로 row_security = off 필요.
create or replace function public.admin_exists()
returns boolean
language sql
stable
security definer
set search_path = public
set row_security = off
as $$
  select exists (select 1 from public.admins);
$$;

revoke all on function public.admin_exists() from public;
grant execute on function public.admin_exists() to anon, authenticated;

alter table public.admins enable row level security;

-- admins: 본인 행 읽기 + 관리자는 전체 읽기 (회원관리 화면에서 관리자 목록 표시용)
drop policy if exists admins_self_or_admin_read on public.admins;
create policy admins_self_or_admin_read
on public.admins
for select
to authenticated
using (
  lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  or (select public.is_admin())
);

-- admins: 테이블이 완전히 비어 있을 때만 누구나(최초 1명) 등록 가능 (부트스트랩)
-- ⚠ with check에 "not exists (select 1 from public.admins)"처럼 admins를 직접
--   서브쿼리로 건드리면 안 된다 — 그 서브쿼리는 INSERT를 실행하는 role(anon/
--   authenticated) 권한으로 평가되어 admins_self_or_admin_read SELECT 정책을
--   다시 트리거하고, 그 정책이 is_admin()을 호출하며 다시 admins를 들여다보는
--   순환이 생겨 "infinite recursion detected in policy for relation admins"
--   (42P17) 에러가 난다. admin_exists()(SECURITY DEFINER + row_security off)를
--   통해서만 존재 여부를 확인해야 이 순환이 끊어진다.
drop policy if exists admins_bootstrap_insert on public.admins;
create policy admins_bootstrap_insert
on public.admins
for insert
to anon, authenticated
with check (not public.admin_exists());

grant select on public.admins to authenticated;
grant insert on public.admins to anon, authenticated;

